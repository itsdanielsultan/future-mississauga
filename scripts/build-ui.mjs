import {readFile, writeFile, mkdir, mkdtemp, rm, copyFile} from 'node:fs/promises';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {gzipSync} from 'node:zlib';
import {execFileSync} from 'node:child_process';
import postcss from 'postcss';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const vendor = join(root, 'node_modules/basecoat-css');
const output = join(root, 'public/vendor/basecoat');
const packageInfo = JSON.parse(await readFile(join(vendor, 'package.json'), 'utf8'));
if (packageInfo.version !== '1.1.0') throw new Error('Use the pinned Basecoat 1.1.0 package.');
const files = ['dist/components/button.css', 'dist/components/input.css',
  'dist/components/native-select.css', 'dist/styles/vega.css'];
const selected = postcss.root();
const sourceProof = [];

// Select the package's real component structures and skin. Field-wrapper aliases,
// other components, and compact variants are intentionally outside this site API.
for (const file of files) {
  const css = await readFile(join(vendor, file), 'utf8');
  sourceProof.push({file, sha256:createHash('sha256').update(css).digest('hex')});
  const parsed = postcss.parse(css, {from:join(vendor, file), map:false});
  parsed.walkRules(rule => {
    if (rule.parent.type !== 'atrule' || rule.parent.name !== 'layer') return;
    const selectors = postcss.list.comma(rule.selector)
      .filter(selector => /^(?:\.btn(?=[\s.:\[]|$)|\.input(?=[\s.:\[]|$)|select\.select(?=[\s.:\[]|$)|:is\(\.field > select, select\.select\))/.test(selector))
      .filter(selector => !/data-size=['"](?:xs|sm|lg|icon-xs|icon-sm|icon-lg)['"]/.test(selector))
      .filter(selector => !/data-variant=['"](?:secondary|link|destructive)['"]/.test(selector));
    if (!selectors.length) return;
    const copy = rule.clone();
    copy.selector = selectors.join(', ').replace(/:is\(\.field > select, select\.select\)/g, 'select.select');
    selected.append(copy);
  });
}

const siteCSS = await readFile(join(root, 'styles/ui-components.css'), 'utf8');
const site = postcss.parse(siteCSS, {from:join(root, 'styles/ui-components.css'), map:false});
// Site sizing deliberately outranks the library's typed-input and size variants.
site.walkRules(rule => { rule.selector = rule.selector.replace(/\.ui-(button|input|select)\b/g, match => match.repeat(2)); });
const input = postcss.root();
for (const node of [...site.nodes]) {
  if (node.type === 'atrule' && ['reference','custom-variant','theme'].includes(node.name)) {
    input.append(node.clone());
    node.remove();
  }
}
input.append(selected.nodes);
input.append(site.nodes);
// Rename library selectors before compilation so its skin and site sizing use
// exactly the same component classes.
input.walkRules(rule => {
  rule.selector = rule.selector.replace(/\.btn\b/g,'.ui-button')
    .replace(/\.input\b/g,'.ui-input').replace(/\.select\b/g,'.ui-select');
});

const temporary = await mkdtemp(join(root, '.ui-build-'));
try {
  const entry = join(temporary, 'input.css');
  const compiled = join(temporary, 'compiled.css');
  await writeFile(entry, input.toString());
  execFileSync(process.execPath, [join(root, 'node_modules/@tailwindcss/cli/dist/index.mjs'),
    '-i', entry, '-o', compiled, '--minify'], {cwd:root, stdio:'pipe'});
  const parsed = postcss.parse(await readFile(compiled, 'utf8'), {from:compiled, map:false});
  // No cascade layer can undercut the site's existing unlayered controls. Keep
  // specificity local to opt-in classes rather than changing unrelated elements.
  parsed.walkAtRules('layer', at => {
    if (at.params === 'properties') at.remove();
    else if (at.nodes) at.replaceWith(at.nodes);
    else at.remove();
  });
  parsed.walkRules(rule => {
    if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
    rule.selector = postcss.list.comma(rule.selector).map(selector => {
      // Nested rules are flattened by Tailwind's optimizer. Every selector must
      // remain component-scoped; reject accidental global/reset output.
      if (!/\.ui-(?:button|input|select)\b/.test(selector)) throw new Error(`Unscoped UI rule: ${selector}`);
      return `html body ${selector.replace(/\.ui-(button|input|select)\b/, match => match.repeat(4))}`;
    }).join(',');
  });
  // Isolate all Tailwind/vendor properties, including its registered internals.
  // The existing site's --accent and --muted have different semantic meanings.
  let css = parsed.toString().replace(/(?<![\w-])--(?!ui-|site-|control-|icon-control-)([a-zA-Z][\w-]*)/g, '--ui-$1');
  css = `/*! Basecoat 1.1.0 selected controls; MIT; see LICENSE.md. Generated by npm run build:ui. */\n${css}\n`;
  if (/@(?:apply|reference|theme)\b/.test(css)) throw new Error('Uncompiled Tailwind directive.');
  await mkdir(output, {recursive:true});
  await writeFile(join(output, 'controls.css'), css);
  await copyFile(join(vendor, 'LICENSE.md'), join(output, 'LICENSE.md'));
  const proof = {schema:'future-mississauga-ui-components/v1', library:'basecoat-css', version:packageInfo.version,
    source:'https://github.com/hunvreus/basecoat', license:'MIT', components:['button','input','native-select'],
    style:'Vega', sourceProof, bytes:Buffer.byteLength(css), gzipBytes:gzipSync(css).length,
    sha256:createHash('sha256').update(css).digest('hex'), runtimeJavaScriptBytes:0,
    globalReset:false, preflight:false, buildCommand:'npm run build:ui'};
  await writeFile(join(output, 'provenance.json'), `${JSON.stringify(proof,null,2)}\n`);
  console.log(`Basecoat controls: ${proof.bytes} bytes (${proof.gzipBytes} gzip), no client JavaScript.`);
} finally {
  await rm(temporary, {recursive:true, force:true});
}
