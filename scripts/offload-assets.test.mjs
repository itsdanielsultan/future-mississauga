async function fixture(t) {
  const stage=await mkdtemp(join(tmpdir(),'asset-delivery-test-'));
  t.after(()=>rm(stage,{recursive:true,force:true}));
  const files = new Map([
    ['models/synthetic.glb',Buffer.from('glTFsynthetic test fixture')],
    ['data/synthetic.json.gz',gzipSync(Buffer.from('{"syntheticFixture":true}'))],
  ]);
  const policy={schema:'future-mississauga-asset-delivery/v3',origin:'https://assets.example.test',assets:[]};
  const proof={schema:'future-mississauga-asset-delivery-proof/v3',origin:policy.origin,legacyRedirectsVerified:true,viewerChecksPassed:true,zeroCostPlanConfirmed:true,syntheticFixture:true,files:[]};
  for (const [path,bytes] of files) {
    const manual=path.endsWith('.gz');
    const row={path,bytes:bytes.length,sha256:sha(bytes),target:`assets/${sha(bytes)}/${basename(path)}`,transport:{mode:manual?'identity':'negotiated-gzip',contentEncoding:manual?null:'gzip'}};
    const encoded=manual?bytes:gzipSync(bytes);
    policy.assets.push(row);
    proof.files.push({syntheticFixture:true,path,url:policy.origin+'/'+row.target,status:200,sha256:row.sha256,bytes:row.bytes,corsAllowed:true,contentEncoding:row.transport.contentEncoding,encodedBytes:encoded.length,encodedSHA256:sha(encoded),wireGzipMagic:true,decodedGLBMagic:!manual});
    await mkdir(join(stage,path,'..'),{recursive:true});
    await writeFile(join(stage,path),bytes);
  }
  const paths={policyPath:join(stage,'synthetic-policy.json'),proofPath:join(stage,'synthetic-proof.json')};
  const save=async()=>{
    await writeFile(paths.policyPath,JSON.stringify(policy));
    await writeFile(paths.proofPath,JSON.stringify(proof));
    await writeFile(join(stage,'asset-delivery-map.js'),`export const assetOrigin = ${JSON.stringify(policy.origin)};\nexport const deliveryPaths = Object.freeze(${JSON.stringify(Object.fromEntries(policy.assets.map(row=>[row.path,row.target])))});\n`);
  };
  const retained=async()=>{for(const path of files.keys())await access(join(stage,path));};
  await save();return {stage,policy,proof,paths,files,save,retained};
}

test('existing negotiated GLB and manual gzip transports retain their behavior', async t => {
  const f=await fixture(t);const result=await offloadValidatedAssets(f.stage,f.paths);
  assert.equal(result.offloadedFiles,2);
  assert.equal(result.offloadedBytes,[...f.files.values()].reduce((sum,b)=>sum+b.length,0));
  for(const path of f.files.keys())await assert.rejects(access(join(f.stage,path)),{code:'ENOENT'});
  const report=JSON.parse(await readFile(join(f.stage,'data/asset-delivery.json'),'utf8'));
  assert.deepEqual(report.assets,f.policy.assets);
  assert.equal(result.sourceFilesRetained,true);
});

